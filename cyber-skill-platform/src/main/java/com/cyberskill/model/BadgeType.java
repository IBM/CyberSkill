package com.cyberskill.model;

/**
 * Enum representing different types of badges
 */
public enum BadgeType {
    SECTION_COMPLETION,     // Awarded for completing a section
    MODULE_COMPLETION,      // Awarded for completing a module
    PATH_COMPLETION,        // Awarded for completing a learning path
    QUIZ_MASTERY,          // Awarded for quiz performance
    STREAK_ACHIEVEMENT,    // Awarded for learning streaks
    TIME_MILESTONE,        // Awarded for time spent learning
    SPECIAL_ACHIEVEMENT    // Special badges for unique accomplishments
}

