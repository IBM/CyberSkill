package com.cyberskill.model;

/**
 * Enum representing different types of quiz questions
 */
public enum QuestionType {
    MULTIPLE_CHOICE,    // Single correct answer from multiple options
    MULTIPLE_SELECT,    // Multiple correct answers from multiple options
    TRUE_FALSE,         // True or False question
    SHORT_ANSWER        // Text-based answer (future enhancement)
}

